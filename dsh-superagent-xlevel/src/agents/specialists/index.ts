export function roleByName(role: string): RoleDefinition {
  const found = ROLES.find((item) => item.role === role);
  if (!found) throw new Error(`Unknown role ${role}`);
  return found;
}

export function toAgentSpec(role: RoleDefinition, enabled = true): AgentSpec {
  return {
    schemaVersion: SCHEMA_VERSION,
    id: `agt_${role.role}`,
    name: role.name,
    role: role.role,
    description: role.mission,
    model: {
      provider: "reference",
      modelId: "dsh-reference-1",
      fallback: ["ollama", "openai-compatible"],
    },
    capabilities: role.capabilities,
    tools: role.tools,
    permissions: {
      filesystem: role.filesystem,
      network: role.network,
      shell: role.shell,
      git: role.git,
    },
    limits: {
      maxSteps: 8,
      maxTokens: 4096,
      timeoutMs: 120_000,
      maxToolCalls: 12,
    },
    policies: ["pol_default_autonomy"],
    promptRef: role.promptRef,
    enabled,
  };
}

export const AGENT_SPECS: AgentSpec[] = ROLES.map((role) => toAgentSpec(role));
