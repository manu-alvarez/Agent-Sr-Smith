"""Funciones compartidas por los scripts de ai/. No es un punto de entrada."""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BEGIN = "<!-- BEGIN SHARED CONTEXT -->"
END = "<!-- END SHARED CONTEXT -->"
PROMPT_HEADER = "<!-- source: {source}; generated by scripts/ai/sync-instructions.py. Do not edit. -->\n"


def read(rel: str) -> str:
    return (ROOT / rel).read_text(encoding="utf-8")


def dump(data: object) -> str:
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


def shared_block() -> str:
    body = read("docs/ai/shared-context.md").rstrip() + "\n"
    return f"{BEGIN}\n{body}{END}\n"


def adapters() -> dict[str, str]:
    shared = shared_block()
    claude = (
        "# Claude Code — Sr.Smith\n\n"
        "Entrada para Claude Code. El bloque compartido lo genera `scripts/ai/sync-instructions.py` "
        "desde `docs/ai/shared-context.md`. No lo edites entre las marcas.\n\n"
        "Trabaja dentro del repositorio. No abras red para cumplir un objetivo `strict-local`. "
        "No pongas `verified: true` sin un probe. Si cambias política, perfiles, fases o prompts, "
        "regenera las proyecciones y deja `npm test` en verde.\n\n"
        f"{shared}"
    )
    gemini = (
        "# Gemini CLI — Sr.Smith\n\n"
        "Entrada para Gemini CLI. El bloque compartido es el mismo que el de `CLAUDE.md` y sale de "
        "`docs/ai/shared-context.md`. No lo edites entre las marcas.\n\n"
        "Los comandos se ejecutan en la raíz del paquete. `python3 scripts/ai/check-context.py` "
        "tiene que pasar antes de dar por cerrado un cambio de proyecciones. No inventes una clave "
        "en `.env.example` ni marques un proveedor remoto como verificado.\n\n"
        f"{shared}"
    )
    return {"CLAUDE.md": claude, "GEMINI.md": gemini}


def prompt_projection() -> dict[str, str]:
    files: dict[str, str] = {}
    for path in sorted((ROOT / "prompts").rglob("*.md")):
        rel = path.relative_to(ROOT).as_posix()
        body = path.read_text(encoding="utf-8")
        if body.startswith("<!-- source:"):
            raise SystemExit(f"{rel} ya tiene cabecera de proyección; el canónico es prompts/")
        files["ai/" + rel] = PROMPT_HEADER.format(source=rel) + body
    return files


def exported_catalogs() -> dict[str, str]:
    script = """
import { AGENT_SPECS } from "./src/agents/specialists/index.ts";
import { PROFILES } from "./src/agents/profiles/index.ts";
import { PHASE_EDGES, TASK_EDGES, PHASE_ORDER } from "./src/core/lifecycle/index.ts";
console.log(JSON.stringify({ specs: AGENT_SPECS, profiles: PROFILES, phases: PHASE_EDGES, tasks: TASK_EDGES, happyPath: PHASE_ORDER }));
"""
    result = subprocess.run(
        ["node", "--experimental-strip-types", "--input-type=module", "-e", script],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    payload = json.loads(result.stdout)
    return {
        "ai/agents/specs.json": dump(payload["specs"]),
        "ai/agents/profiles.json": dump(payload["profiles"]),
        "ai/workflows/phases.json": dump(
            {
                "schemaVersion": "1.0.0",
                "source": "src/core/lifecycle/index.ts",
                "phases": payload["phases"],
                "tasks": payload["tasks"],
                "happyPath": payload["happyPath"],
            }
        ),
    }


def schema_catalog() -> str:
    entries = []
    for path in sorted((ROOT / "schemas").rglob("*.schema.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        entries.append(
            {
                "path": path.relative_to(ROOT).as_posix(),
                "id": data.get("$id"),
                "title": data.get("title"),
                "required": data.get("required", []),
            }
        )
    return dump({"schemaVersion": "1.0.0", "canonicalRoot": "schemas", "schemas": entries})


def generated() -> dict[str, str]:
    files: dict[str, str] = {}
    files.update(adapters())
    files.update(prompt_projection())
    files.update(exported_catalogs())
    files["ai/schemas/catalog.json"] = schema_catalog()
    files["ai/tools/native.json"] = read("config/tools/native.json")
    files["ai/providers/registry.json"] = read("config/models/providers.json")
    return files


def diff(files: dict[str, str]) -> list[str]:
    problems = []
    for rel, content in files.items():
        path = ROOT / rel
        if not path.exists():
            problems.append(f"falta {rel}")
            continue
        if path.read_text(encoding="utf-8") != content:
            problems.append(f"diverge {rel}")
    return problems
